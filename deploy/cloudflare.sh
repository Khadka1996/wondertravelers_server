#!/usr/bin/env bash
# deploy/cloudflare.sh - run as root after every domain is proxied (orange cloud).
#   cloudflare.sh realip    write nginx's list of Cloudflare addresses (safe any time)
#   cloudflare.sh firewall  allow ports 80/443 ONLY from Cloudflare, so nobody can skip it
set -euo pipefail
v4=$(curl -fsS https://www.cloudflare.com/ips-v4)
v6=$(curl -fsS https://www.cloudflare.com/ips-v6)

case "${1:-}" in
  realip)
    {
      echo "# Generated by deploy/cloudflare.sh - visitor IP from Cloudflare's header."
      for ip in $v4 $v6; do echo "set_real_ip_from $ip;"; done
      echo "real_ip_header CF-Connecting-IP;"
    } > /etc/nginx/conf.d/cloudflare-realip.conf
    # nginx.conf had an older partial list; one source of truth is enough.
    sed -i '/^set_real_ip_from /d; /^real_ip_header /d' /etc/nginx/nginx.conf
    nginx -t && systemctl reload nginx
    ;;
  firewall)
    ufw allow 22/tcp
    for port in 80 443; do
      ufw delete allow "$port" >/dev/null 2>&1 || true
      ufw delete allow "$port/tcp" >/dev/null 2>&1 || true
      ufw delete allow "Nginx Full" >/dev/null 2>&1 || true
      for ip in $v4 $v6; do ufw allow proto tcp from "$ip" to any port "$port" >/dev/null; done
    done
    ufw reload
    ufw status | head -20
    ;;
  *) echo "usage: $0 realip|firewall" >&2; exit 1 ;;
esac
